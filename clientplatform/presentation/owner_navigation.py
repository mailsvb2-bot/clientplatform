from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class OwnerNavItem:
    label: str
    need: str


def choice_help(*items: OwnerNavItem, intro: str = "Если Вам нужно:") -> str:
    return intro + "\n" + "\n".join(
        f"• {item.need} → «{item.label}»" for item in items
    )


